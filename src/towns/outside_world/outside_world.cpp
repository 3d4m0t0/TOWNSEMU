void Outside_World::WindowInterface::Print(int x0,const char str[])
{
	for(unsigned char *ustr=(unsigned char *)str; 0!=*ustr; ++ustr)
	{
		auto *ptn=font10x14[*ustr];
		for(int y=0; y<14; ++y)
		{
			auto dstPtr=winThr.statusBitmap+(STATUS_WID*(y+1)+x0)*4;
			unsigned short linePtn=*ptn;
			linePtn<<=8;
			linePtn|=*(ptn+1);
			for(int x=0; x<10; ++x)
			{
				if(linePtn&0x8000)
				{
					memset(dstPtr,255,4);
				}
				else
				{
					memset(dstPtr,0,4);
				}
				linePtn<<=1;
				dstPtr+=4;
			}
			ptn+=4;
		}
		x0+=10;
	}
}
